const assert=require('node:assert/strict');
require('../battle-attacks.js');require('../battle-roots.js');
const R=BattleRoots,p={u:.5,v:.75,jump:0},near=r=>({u:r.x/12+.5,v:r.y/8,jump:0});
const state=R.create(),root=R.beginTurn(state,p,()=>.9)[0];
assert.ok(Math.hypot(root.x,root.y-6)>=R.settings.spawnSafety);
assert.equal(state.roots.length,1);assert.equal(R.status(state).roots[0].remainingTurns,2);
for(let i=0;i<20;i++)assert.deepEqual(R.step(state,.05,p),[]);
assert.equal(root.mode,'idle');
const target=near(root);assert.deepEqual(R.step(state,.05,target),[]);assert.equal(root.mode,'windup');
for(let i=0;i<4;i++)assert.deepEqual(R.step(state,.05,target),[]);
const jump=structuredClone(state),jumping={...target,jump:.31};
assert.deepEqual(R.step(jump,.1,jumping),[],'jump must clear a root strike');
assert.ok(R.step(state,.1,target).some(h=>h.id===root.id&&h.damage===5));
assert.ok(R.entities(state)[0].active);
R.endTurn(state);assert.equal(state.roots.length,1);assert.equal(R.status(state).roots[0].remainingTurns,1);
assert.equal(R.entities(state)[0].active,false);
const frozen=structuredClone(state);R.step(state,.1,target);assert.deepEqual(state,frozen,'no ticking or damage in the hero turn');
const second=R.beginTurn(state,p,()=>.9)[0];
assert.equal(state.roots.length,2);assert.equal(R.status(state).roots.find(r=>r.id===root.id).remainingTurns,1);
assert.ok(Math.hypot(root.x-second.x,root.y-second.y)>=R.settings.rootSeparation);
R.endTurn(state);assert.deepEqual(state.roots.map(r=>r.id),[second.id]);
R.beginTurn(state,p,()=>.1);assert.equal(state.roots.length,3);assert.ok(!state.roots.some(r=>r.id===root.id));
for(let i=0;i<45;i++){
 R.endTurn(state);const pp={u:.04+(i%11)/11*.92,v:.1+(i%9)/9*.86,jump:0};
 const created=R.beginTurn(state,pp,()=>i%3/2),pt=FlowerAttacks.playerPoint(pp);
 assert.equal(created.length,R.spawnCount(state.turn));
 for(const r of created)assert.ok(Math.hypot(r.x-pt.x,r.y-pt.y)>=2);
 assert.ok(state.roots.every(r=>r.bornTurn>=state.turn-1));
}
assert.deepEqual([1,2,3,4,5,6,7,8,9].map(R.spawnCount),[1,1,2,2,2,3,3,3,4]);
console.log('PASS roots: safe spawns, exact 5 damage, proximity tell/strike, jump, two-turn lifetime, hero-turn freeze and third-turn growth without crowding stalls');
